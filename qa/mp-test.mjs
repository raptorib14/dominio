import { chromium } from "playwright";
const URL = process.env.URL || "http://127.0.0.1:4173/";
const args = ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"];
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) process.exitCode = 1; };
const bA = await chromium.launch({ args }), bB = await chromium.launch({ args });
const host = await bA.newPage({ viewport: { width: 1280, height: 720 } });
const guest = await bB.newPage({ viewport: { width: 844, height: 390 }, hasTouch: true, isMobile: true });
for (const [n,p] of [["host",host],["guest",guest]]) p.on("pageerror", e => console.log(n, "PAGEERR", e.message));
const map = process.env.MAP || "MUELLE";
await host.goto(URL); await guest.goto(URL);
await host.waitForFunction(() => !!window.__controlsTest, null, { timeout: 30000 });
await host.getByText(map, { exact: true }).first().click();
await host.getByRole("textbox").first().fill("Nico");
await guest.getByRole("textbox").first().fill("Amigo");
await host.getByRole("button", { name: "CREAR SALA" }).click();
await host.waitForTimeout(500);
const code = (await host.locator("p.font-display.text-2xl").innerText()).trim();
ok(/^[A-Z0-9]{4}$/.test(code), "room code " + code);
await host.waitForFunction(() => /Sala abierta/.test(document.body.innerText), null, { timeout: 20000 });
await guest.getByPlaceholder("CÓDIGO").fill(code);
await guest.getByRole("button", { name: "UNIRSE" }).click();
await host.waitForFunction(() => /Enlace con Amigo/.test(document.body.innerText), null, { timeout: 30000 });
await guest.waitForFunction(() => /Enlace con Nico/.test(document.body.innerText), null, { timeout: 30000 });
ok(true, "both linked via PeerJS");
await host.getByRole("button", { name: "DESPLEGAR COOP" }).click();
await guest.waitForFunction(() => window.__controlsTest.getPhase() === "play", null, { timeout: 15000 });
ok(true, "guest entered play after host deploy");
await host.evaluate(() => window.__controlsTest.setKeys(["KeyW"]));
await host.waitForTimeout(2500);
await host.evaluate(() => window.__controlsTest.setKeys([]));
const hp = await host.evaluate(() => window.__controlsTest.getPos());
await host.waitForTimeout(800);
const remote = await guest.evaluate(() => window.__controlsTest.getRemote?.());
ok(remote && Math.hypot(remote.x - hp.x, remote.z - hp.z) < 1.0, `guest sees host at ${JSON.stringify(remote)} vs ${JSON.stringify(hp)}`);
const hb = await host.evaluate(() => window.__controlsTest.getBots().map(b=>[+b.x.toFixed(1),+b.z.toFixed(1)]));
const gb = await guest.evaluate(() => window.__controlsTest.getBots().map(b=>[+b.x.toFixed(1),+b.z.toFixed(1)]));
const diff = Math.max(...hb.map((b,i)=>Math.hypot(b[0]-gb[i][0], b[1]-gb[i][1])));
ok(diff < 3, "bots in sync, max drift " + diff.toFixed(2));
const gmap = await guest.evaluate(() => window.__controlsTest.getMap?.());
ok(gmap === map.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, ""), "guest map " + gmap);
// guest shoots bot -> host bot loses hp
const tgt = await host.evaluate(() => { const b = window.__controlsTest.getBots().findIndex(b=>b.alive); return b; });
if (process.env.THIRD) {
  const bC = await chromium.launch({ args });
  const third = await bC.newPage();
  await third.goto(URL);
  await third.waitForFunction(() => !!window.__controlsTest, null, { timeout: 30000 });
  await third.getByPlaceholder("CÓDIGO").fill(code);
  await third.getByRole("button", { name: "UNIRSE" }).click();
  await third.waitForFunction(() => /sala está llena/.test(document.body.innerText), null, { timeout: 20000 }).then(() => ok(true, "third player told room is full"), () => ok(false, "third player full msg"));
  await bC.close();
}
await host.screenshot({ path: `capturas/coop-host-${map.toLowerCase()}.png` });
await guest.screenshot({ path: `capturas/coop-guest-movil-${map.toLowerCase()}.png` });
await bA.close(); await bB.close();
